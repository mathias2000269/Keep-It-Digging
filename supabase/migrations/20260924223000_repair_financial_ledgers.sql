-- Repara y sincroniza los historiales contables.
-- Los historiales sobreviven al borrado de las tarjetas operativas.

create table if not exists public.revenue_ledger (
  id bigint generated by default as identity primary key,
  order_id uuid not null unique,
  customer_name text not null,
  amount numeric(12,2) not null check (amount >= 0),
  completed_at timestamptz not null default now()
);

create table if not exists public.expense_ledger (
  id bigint generated by default as identity primary key,
  expense_id uuid not null unique,
  amount numeric(12,2) not null check (amount > 0),
  concept text not null,
  created_by_name text not null,
  spent_at timestamptz not null,
  cancelled_at timestamptz
);

create index if not exists revenue_completed_idx
on public.revenue_ledger (completed_at desc);

create index if not exists expense_ledger_spent_idx
on public.expense_ledger (spent_at desc);

create index if not exists expense_ledger_active_idx
on public.expense_ledger (spent_at desc)
where cancelled_at is null;

alter table public.revenue_ledger enable row level security;
alter table public.expense_ledger enable row level security;

drop policy if exists "revenue_management_read" on public.revenue_ledger;
create policy "revenue_management_read" on public.revenue_ledger
for select to authenticated
using ((select private.is_admin()));

drop policy if exists "expense_ledger_management_read" on public.expense_ledger;
create policy "expense_ledger_management_read" on public.expense_ledger
for select to authenticated
using ((select private.is_admin()));

grant select on public.revenue_ledger to authenticated;
grant select on public.expense_ledger to authenticated;

create or replace function private.record_completed_order_revenue()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' and new.status = 'completed' then
    insert into public.revenue_ledger (
      order_id,
      customer_name,
      amount,
      completed_at
    )
    values (
      new.id,
      new.customer_name,
      new.total,
      now()
    )
    on conflict (order_id) do nothing;
  elsif tg_op = 'UPDATE'
        and new.status = 'completed'
        and old.status is distinct from 'completed' then
    insert into public.revenue_ledger (
      order_id,
      customer_name,
      amount,
      completed_at
    )
    values (
      new.id,
      new.customer_name,
      new.total,
      now()
    )
    on conflict (order_id) do nothing;
  elsif tg_op = 'UPDATE'
        and old.status = 'completed'
        and new.status is distinct from 'completed' then
    delete from public.revenue_ledger
    where order_id = new.id;
  end if;

  return new;
end;
$$;

revoke all on function private.record_completed_order_revenue()
from public, anon, authenticated;

drop trigger if exists record_completed_order_revenue on public.orders;
create trigger record_completed_order_revenue
after insert or update of status on public.orders
for each row execute function private.record_completed_order_revenue();

-- Recupera los ingresos de pedidos que ya estaban completados.
insert into public.revenue_ledger (
  order_id,
  customer_name,
  amount,
  completed_at
)
select
  id,
  customer_name,
  total,
  created_at
from public.orders
where status = 'completed'
on conflict (order_id) do nothing;

-- Retira ingresos añadidos por error si el pedido todavía existe y se reabrió.
-- No afecta a pedidos completados que ya fueron borrados de la lista.
delete from public.revenue_ledger as ledger
using public.orders as order_row
where ledger.order_id = order_row.id
  and order_row.status is distinct from 'completed';

-- Recupera los tickets de gasto que ya existieran.
insert into public.expense_ledger (
  expense_id,
  amount,
  concept,
  created_by_name,
  spent_at,
  cancelled_at
)
select
  id,
  amount,
  concept,
  created_by_name,
  created_at,
  cancelled_at
from public.expenses
on conflict (expense_id) do update
set amount = excluded.amount,
    concept = excluded.concept,
    created_by_name = excluded.created_by_name,
    spent_at = excluded.spent_at,
    cancelled_at = excluded.cancelled_at;

create or replace function public.create_expense(
  p_amount numeric,
  p_concept text
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_expense_id uuid;
  v_name text;
begin
  if not private.is_admin() then
    raise exception 'Acceso denegado';
  end if;

  if p_amount is null or p_amount <= 0 then
    raise exception 'El importe debe ser mayor que cero';
  end if;

  if char_length(trim(coalesce(p_concept, ''))) not between 2 and 500 then
    raise exception 'Escribe un concepto valido';
  end if;

  select full_name into v_name
  from public.profiles
  where id = (select auth.uid());

  if v_name is null then
    raise exception 'Perfil no encontrado';
  end if;

  insert into public.expenses (
    amount,
    concept,
    created_by,
    created_by_name
  )
  values (
    round(p_amount, 2),
    trim(p_concept),
    (select auth.uid()),
    v_name
  )
  returning id into v_expense_id;

  insert into public.expense_ledger (
    expense_id,
    amount,
    concept,
    created_by_name,
    spent_at
  )
  values (
    v_expense_id,
    round(p_amount, 2),
    trim(p_concept),
    v_name,
    now()
  );

  return v_expense_id;
end;
$$;

create or replace function public.cancel_expense(p_expense_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.is_admin() then
    raise exception 'Acceso denegado';
  end if;

  update public.expenses
  set cancelled_at = now(),
      cancelled_by = (select auth.uid())
  where id = p_expense_id
    and cancelled_at is null;

  if not found then
    raise exception 'Ticket no encontrado o ya cancelado';
  end if;

  update public.expense_ledger
  set cancelled_at = now()
  where expense_id = p_expense_id
    and cancelled_at is null;
end;
$$;

create or replace function public.delete_expense(p_expense_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.is_admin() then
    raise exception 'Acceso denegado';
  end if;

  delete from public.expenses
  where id = p_expense_id;

  if not found then
    raise exception 'Ticket no encontrado';
  end if;
end;
$$;

revoke all on function public.create_expense(numeric, text) from public, anon;
revoke all on function public.cancel_expense(uuid) from public, anon;
revoke all on function public.delete_expense(uuid) from public, anon;
grant execute on function public.create_expense(numeric, text) to authenticated;
grant execute on function public.cancel_expense(uuid) to authenticated;
grant execute on function public.delete_expense(uuid) to authenticated;
